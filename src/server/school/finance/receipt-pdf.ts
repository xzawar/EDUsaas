import 'server-only';
import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from 'pdf-lib';
import { amountInWords, formatPKR } from '@/lib/money';
import { periodLabel } from '@/lib/periods';
import type { AuthedContext } from '@/server/http/route';
import { sectionLabel } from '@/server/school/common';
import { paymentForReceipt } from '@/server/school/finance/payments';

/** Standard fonts are Latin-1; anything else becomes '?'. Matches the report-card renderer. */
const latin = (s: string) => s.replace(/[^\x20-\x7E\xA0-\xFF]/g, '?');

export type ReceiptData = {
  school: { name: string; city: string | null };
  receiptNumber: string;
  receivedOn: string;
  reversed: boolean;
  isReversal: boolean;
  student: {
    name: string;
    username: string | null;
    section: string | null;
    rollNumber: number | null;
    guardian: string | null;
  };
  amountPaisa: number;
  method: string;
  reference: string | null;
  lines: { label: string; amountPaisa: number }[];
  advancePaisa: number;
  receivedBy: string;
  note: string | null;
  footer: string | null;
};

const METHOD_LABEL: Record<string, string> = {
  CASH: 'Cash',
  BANK: 'Bank transfer',
  JAZZCASH: 'JazzCash',
  EASYPAISA: 'Easypaisa',
  CHEQUE: 'Cheque',
};

export async function renderReceipt(r: ReceiptData): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.setTitle(latin(`Receipt ${r.receiptNumber}`));
  pdf.setProducer('EDUsaas');
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.06, 0.09, 0.16);
  const muted = rgb(0.39, 0.45, 0.55);
  const line = rgb(0.89, 0.91, 0.94);
  const accent = rgb(0.06, 0.46, 0.43);
  const M = 40;
  const page: PDFPage = pdf.addPage([595.28, 420]); // A5 landscape-ish slip
  const W = page.getWidth() - M * 2;
  let y = page.getHeight() - M;
  const text = (t: string, x: number, size = 10, f: PDFFont = font, color = ink) =>
    page.drawText(latin(t), { x, y, size, font: f, color });
  const right = (t: string, size = 10, f: PDFFont = font, color = ink) =>
    page.drawText(latin(t), { x: M + W - f.widthOfTextAtSize(latin(t), size), y, size, font: f, color });

  text(r.school.name.toUpperCase(), M, 9, bold, accent);
  right(r.isReversal ? 'PAYMENT REVERSAL' : 'FEE RECEIPT', 9, bold, r.isReversal ? rgb(0.7, 0.15, 0.15) : accent);
  y -= 22;
  text(r.receiptNumber, M, 20, bold);
  right(`Date: ${r.receivedOn}`, 10, font, muted);
  if (r.reversed) {
    y -= 16;
    text('REVERSED - this receipt is no longer valid', M, 10, bold, rgb(0.7, 0.15, 0.15));
  }
  y -= 18;
  page.drawLine({ start: { x: M, y }, end: { x: M + W, y }, thickness: 1, color: line });
  y -= 18;

  const row = (label: string, value: string) => {
    text(label, M, 9, font, muted);
    text(value, M + 110, 10);
    y -= 16;
  };
  row('Student', `${r.student.name}${r.student.username ? `  (${r.student.username})` : ''}`);
  row('Class', `${r.student.section ?? '-'}${r.student.rollNumber ? `  Roll no. ${r.student.rollNumber}` : ''}`);
  if (r.student.guardian) row('Guardian', r.student.guardian);
  row('Paid by', `${METHOD_LABEL[r.method] ?? r.method}${r.reference ? `  Ref: ${r.reference}` : ''}`);
  y -= 6;
  page.drawLine({ start: { x: M, y }, end: { x: M + W, y }, thickness: 1, color: line });
  y -= 18;

  for (const l of r.lines) {
    text(l.label, M, 10);
    right(formatPKR(l.amountPaisa), 10);
    y -= 16;
  }
  if (r.advancePaisa > 0) {
    text('Kept on account for next bill', M, 10, font, muted);
    right(formatPKR(r.advancePaisa), 10, font, muted);
    y -= 16;
  }
  y -= 4;
  page.drawLine({ start: { x: M, y }, end: { x: M + W, y }, thickness: 1, color: line });
  y -= 20;
  text('Amount received', M, 11, bold);
  right(formatPKR(r.amountPaisa), 14, bold);
  y -= 16;
  text(amountInWords(r.amountPaisa), M, 9, font, muted);
  y -= 24;
  if (r.note) {
    text(`Note: ${r.note}`, M, 9, font, muted);
    y -= 14;
  }
  text(`Received by ${r.receivedBy}`, M, 9, font, muted);
  right('Generated by EDUsaas', 8, font, muted);
  if (r.footer) {
    y -= 14;
    text(r.footer, M, 8, font, muted);
  }
  return pdf.save();
}

export async function receiptPdf(ctx: AuthedContext, paymentId: string) {
  const { payment: p, tenant, settings, receivedBy } = await paymentForReceipt(ctx, paymentId);
  const amount = Math.abs(Number(p.amountPaisa));
  const allocated = p.allocations.reduce((a, x) => a + Number(x.amountPaisa), 0);
  const data: ReceiptData = {
    school: { name: tenant.name, city: tenant.city },
    receiptNumber: p.receiptNumber,
    receivedOn: p.receivedOn.toISOString().slice(0, 10),
    reversed: !!p.reversedByPaymentId,
    isReversal: !!p.reversesPaymentId,
    student: {
      name: p.student.user.displayName,
      username: p.student.user.username,
      section: p.student.section ? sectionLabel(p.student.section) : null,
      rollNumber: p.student.rollNumber,
      guardian: p.student.guardianName,
    },
    amountPaisa: amount,
    method: p.method,
    reference: p.reference,
    lines: p.allocations.length
      ? p.allocations.map((a) => ({
          label: `Fee bill ${a.invoice.number} - ${periodLabel(a.invoice.period)}`,
          amountPaisa: Number(a.amountPaisa),
        }))
      : [{ label: p.reversesPaymentId ? 'Reversal' : 'On account (advance)', amountPaisa: amount }],
    advancePaisa: p.reversesPaymentId ? 0 : Math.max(0, amount - allocated),
    receivedBy,
    note: p.note ?? p.reversalReason,
    footer: settings.receiptFooter,
  };
  const bytes = await renderReceipt(data);
  return new Response(new Uint8Array(bytes), {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `inline; filename="receipt-${p.receiptNumber}.pdf"`,
      'Cache-Control': 'no-store',
      'X-Content-Type-Options': 'nosniff',
    },
  });
}
