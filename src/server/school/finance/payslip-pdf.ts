import 'server-only';
import { PDFDocument, StandardFonts, rgb, type PDFFont } from 'pdf-lib';
import { amountInWords, formatPKR } from '@/lib/money';
import { periodLabel } from '@/lib/periods';
import type { AuthedContext } from '@/server/http/route';
import { payslipForPdf } from '@/server/school/finance/payroll';

const latin = (s: string) => s.replace(/[^\x20-\x7E\xA0-\xFF]/g, '?');

export async function payslipPdf(ctx: AuthedContext, id: string) {
  const { slip, period, status, school } = await payslipForPdf(ctx, id);
  const pdf = await PDFDocument.create();
  pdf.setTitle(latin(`Payslip ${slip.number}`));
  pdf.setProducer('EDUsaas');
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.06, 0.09, 0.16);
  const muted = rgb(0.39, 0.45, 0.55);
  const line = rgb(0.89, 0.91, 0.94);
  const accent = rgb(0.06, 0.46, 0.43);
  const M = 48;
  const page = pdf.addPage([595.28, 841.89]);
  const W = page.getWidth() - M * 2;
  let y = page.getHeight() - M;
  const text = (t: string, x: number, size = 10, f: PDFFont = font, color = ink) =>
    page.drawText(latin(t), { x, y, size, font: f, color });
  const right = (t: string, size = 10, f: PDFFont = font, color = ink) =>
    page.drawText(latin(t), { x: M + W - f.widthOfTextAtSize(latin(t), size), y, size, font: f, color });
  const rule = () => {
    page.drawLine({ start: { x: M, y }, end: { x: M + W, y }, thickness: 1, color: line });
  };

  text(school.name.toUpperCase(), M, 9, bold, accent);
  right(status === 'DRAFT' ? 'DRAFT PAYSLIP' : 'PAYSLIP', 9, bold, accent);
  y -= 24;
  text(periodLabel(period), M, 20, bold);
  right(slip.number, 11, bold, muted);
  y -= 22;
  text(slip.name, M, 12, bold);
  right(slip.paidOn ? `Paid ${slip.paidOn}${slip.method ? ` by ${slip.method}` : ''}` : 'Not paid yet', 9, font, muted);
  y -= 16;
  rule();
  y -= 20;

  const row = (label: string, value: number, f: PDFFont = font, color = ink) => {
    text(label, M, 10, f, color);
    right(formatPKR(value), 10, f, color);
    y -= 16;
  };
  text('Earnings', M, 9, bold, muted);
  y -= 14;
  row('Basic salary', slip.basicPaisa);
  for (const a of slip.allowances) row(a.name, a.amountPaisa);
  y -= 6;
  text('Deductions', M, 9, bold, muted);
  y -= 14;
  for (const d of slip.deductions) row(d.name, -d.amountPaisa);
  if (slip.unpaidLeaveDays > 0)
    row(
      `Unpaid leave (${slip.unpaidLeaveDays} day${slip.unpaidLeaveDays === 1 ? '' : 's'})`,
      -slip.leaveDeductionPaisa,
    );
  if (!slip.deductions.length && slip.unpaidLeaveDays === 0) {
    text('None', M, 10, font, muted);
    y -= 16;
  }
  y -= 4;
  rule();
  y -= 20;
  text('Net pay', M, 12, bold);
  right(formatPKR(slip.netPaisa), 14, bold);
  y -= 16;
  text(amountInWords(slip.netPaisa), M, 9, font, muted);
  y -= 30;
  text('Generated by EDUsaas. Keep this for your records.', M, 8, font, muted);

  const bytes = await pdf.save();
  return new Response(new Uint8Array(bytes), {
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `inline; filename="payslip-${slip.number}.pdf"`,
      'Cache-Control': 'no-store',
      'X-Content-Type-Options': 'nosniff',
    },
  });
}
